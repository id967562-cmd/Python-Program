a=10
b=5
print("Arithmatic Operator\n")
print(a+b)
print(a-b)
print(a*b)
print(a/b)
print(a%b)
print(a**b) #Power operator
print(a//b) #Floor operator

print("Comparison Operators\n")
print(a==b)
print(a!=b)
print(a>b)
print(a<b)
print(a>=b)
print(a<=b)

print("Logical Operator")
age=23
print(age>28 and age<30)
print(age<18 or age>18)
